<#
.SYNOPSIS
    Vista Platform Device Agent installer for Windows.

.DESCRIPTION
    Windows counterpart to install-device-agent.sh. Installs the device agent
    as a Windows service that starts on boot and restarts on failure, writes
    its configuration readable by Administrators and SYSTEM only, starts it,
    and waits for the agent to enroll itself with the platform.

    The installer does not register the agent: the agent enrolls itself on
    first start with the registration key in its configuration. Re-running the
    installer with the same key keeps the agent's enrollment and replaces only
    the binary, which is how to upgrade it. A different key is a fresh
    enrollment.

    Run it from the directory that holds the device agent: device-agent.exe
    from the release package, or the release file
    vista-device-agent_<version>_windows_<arch>.exe as downloaded.

.EXAMPLE
    .\install-device-agent.ps1 -Url https://vista.example.com -KeyStdin

    Prompts for the registration key, so it does not appear on the command
    line or in the process list.

.EXAMPLE
    $env:VISTA_REGISTRATION_KEY = "REG-..."; .\install-device-agent.ps1 -Url https://vista.example.com

.EXAMPLE
    .\install-device-agent.ps1 -Url https://vista.example.com -Key REG-... -CaFingerprint 3f9a...

    For a platform whose certificate is signed by a private CA this host does
    not trust: the agent pins the platform's CA only if it has this SHA-256
    fingerprint.

.EXAMPLE
    .\install-device-agent.ps1 -CheckDependencies

    Checks that the agent binary runs on this host, then exits. Needs neither
    Administrator rights nor a key.

.NOTES
    Must be run from an elevated (Administrator) PowerShell session, except
    with -CheckDependencies.
#>

[CmdletBinding()]
param(
    # Platform URL, as shown in the console. Required.
    [string]$Url = "",

    # Registration key minted in the console. A key on the command line is
    # visible to other users in the process list; prefer -KeyStdin or the
    # VISTA_REGISTRATION_KEY environment variable.
    [string]$Key = "",

    # Read the registration key from standard input (the first line) when it
    # is redirected, otherwise prompt for it without echoing it.
    [switch]$KeyStdin,

    # Expected SHA-256 fingerprint of the platform's CA certificate, for a
    # platform whose certificate this host does not already trust.
    [string]$CaFingerprint = "",

    # Install location. The service, its configuration and its data live here.
    [string]$InstallDir = "$env:ProgramFiles\VistaDeviceAgent",

    # Check that the agent binary runs on this host, then exit.
    [switch]$CheckDependencies
)

$ErrorActionPreference = "Stop"
$ServiceName = "VistaDeviceAgent"
$ServiceDisplay = "Vista Platform Device Agent"

function Write-Info  { param($m) Write-Host "[INFO]  $m" -ForegroundColor Green }
function Write-Warn  { param($m) Write-Host "[WARN]  $m" -ForegroundColor Yellow }
function Write-Err   { param($m) Write-Host "[ERROR] $m" -ForegroundColor Red }

#region agent-config
# Shared with cmd/device-agent/installer_config_ps1_test.go, which runs these
# functions under PowerShell against the agent's own config loader and writer.

# The binary's name in the release package (and once installed), and the
# release's own name for the loose download.
$InstalledBinaryName = "device-agent.exe"
$ReleaseBinaryPattern = "vista-device-agent_*_windows_*.exe"

# Single-quoted YAML scalar: backslashes are literal, a quote is doubled, and a
# "#" or ": " in a value cannot break the file.
function ConvertTo-YamlScalar([string]$v) { "'" + $v.Replace("'", "''") + "'" }

# The configuration the installer writes. It leaves the agent unenrolled: the
# agent enrolls itself with the key on first start and rewrites this file with
# its agent ID. The data path is inside the install directory.
function New-AgentConfigText([string]$url, [string]$key, [string]$dataDir) {
    @"
# Vista Platform Device Agent configuration (generated by install-device-agent.ps1)
platform_url: $(ConvertTo-YamlScalar $url)
registration_key: $(ConvertTo-YamlScalar $key)
poll_interval: 30s
data_path: $(ConvertTo-YamlScalar $dataDir)
"@
}

# Value of a top-level `key: value` line in the agent config. The installer
# writes single-quoted values and the agent rewrites them double-quoted; both
# are decoded.
function Get-ConfigValue([string]$path, [string]$key) {
    if (-not (Test-Path -LiteralPath $path)) { return $null }
    $line = Get-Content -LiteralPath $path | Where-Object { $_ -match "^${key}:" } | Select-Object -First 1
    if (-not $line) { return $null }
    $v = ($line -replace "^${key}:\s*", '').Trim()
    if ($v.Length -ge 2 -and $v.StartsWith('"') -and $v.EndsWith('"')) {
        return $v.Substring(1, $v.Length - 2).Replace('\"', '"').Replace('\\', '\')
    }
    if ($v.Length -ge 2 -and $v.StartsWith("'") -and $v.EndsWith("'")) {
        return $v.Substring(1, $v.Length - 2).Replace("''", "'")
    }
    return $v
}

function Get-KeySha256([string]$value) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try { return ([System.BitConverter]::ToString($sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($value))) -replace '-', '').ToLowerInvariant() }
    finally { $sha.Dispose() }
}

# True when the config at $path records that this host enrolled with $key:
# the key itself (until the platform has issued the per-agent secret that
# replaces it) or its SHA-256 fingerprint, which is all the agent keeps after.
function Test-EnrolledWithKey([string]$path, [string]$key) {
    $uuidPattern = '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'
    if (-not ((Get-ConfigValue $path 'agent_id') -match $uuidPattern)) { return $false }
    if ((Get-ConfigValue $path 'registration_key') -eq $key) { return $true }
    return ((Get-ConfigValue $path 'registration_key_sha256') -eq (Get-KeySha256 $key))
}

# The agent binary beside this script: the name the release package uses, or
# exactly one file with the release's own name, as downloaded.
function Find-AgentBinary([string]$dir) {
    $installed = Join-Path $dir $InstalledBinaryName
    if (Test-Path -LiteralPath $installed -PathType Leaf) { return $installed }
    $released = @(Get-ChildItem -LiteralPath $dir -Filter $ReleaseBinaryPattern -File -ErrorAction SilentlyContinue)
    if ($released.Count -eq 1) { return $released[0].FullName }
    if ($released.Count -gt 1) {
        throw "Found $($released.Count) files named $ReleaseBinaryPattern in $dir ($(($released | ForEach-Object { $_.Name }) -join ', ')). Keep the one for this host, or rename it to $InstalledBinaryName."
    }
    throw "No device agent binary in $dir. Put $InstalledBinaryName (from the release package) or the downloaded $ReleaseBinaryPattern next to this script."
}
#endregion agent-config

# --- The binary runs on this host ------------------------------------------
# Running it proves it is a build for this architecture. -version exits before
# configuration or enrollment.
try {
    $BinarySource = Find-AgentBinary $PSScriptRoot
} catch {
    Write-Err $_.Exception.Message
    exit 1
}
$AgentVersion = $null
try {
    $versionOutput = @(& $BinarySource -version 2>$null)
    if ($LASTEXITCODE -eq 0 -and $versionOutput.Count -gt 0 -and "$($versionOutput[0])" -match ' v(\S+)$') { $AgentVersion = $Matches[1] }
} catch { }
if (-not $AgentVersion) {
    Write-Err "The device agent ($BinarySource) cannot run on this host. Installation stopped before anything was changed."
    Write-Err "Check that it is the Windows build for this host's architecture."
    exit 1
}
if ($CheckDependencies) {
    Write-Info "Device agent v$AgentVersion runs on this host."
    exit 0
}

# --- Arguments -------------------------------------------------------------
if ($KeyStdin) {
    if ([Console]::IsInputRedirected) {
        $Key = [Console]::In.ReadLine()
    } else {
        $secure = Read-Host -AsSecureString "Registration key"
        $Key = [System.Net.NetworkCredential]::new("", $secure).Password
    }
}
if ([string]::IsNullOrEmpty($Key) -and $env:VISTA_REGISTRATION_KEY) { $Key = $env:VISTA_REGISTRATION_KEY }
if ($null -ne $Key) { $Key = $Key.Trim() }
if ([string]::IsNullOrWhiteSpace($Url) -or [string]::IsNullOrWhiteSpace($Key)) {
    Write-Err "-Url and a registration key are required (-Key, -KeyStdin, or VISTA_REGISTRATION_KEY in the environment)."
    Write-Host "  Example: .\install-device-agent.ps1 -Url https://vista.example.com -KeyStdin"
    exit 1
}
if ($CaFingerprint) {
    # The agent's own normalisation: case, an optional sha256: prefix and
    # separators do not matter.
    $normalized = ($CaFingerprint.Trim().ToLowerInvariant() -replace '^sha256:', '') -replace '[:\s-]', ''
    if ($normalized -notmatch '^[0-9a-f]{64}$') {
        Write-Err "-CaFingerprint must be a SHA-256 fingerprint: 64 hexadecimal characters (colons allowed)."
        exit 1
    }
    $CaFingerprint = $normalized
}

$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-Err "This installer must be run from an elevated (Administrator) PowerShell session."
    exit 1
}

$maskedKey = if ($Key.Length -le 4) { "****" } else { "****" + $Key.Substring($Key.Length - 4) }

Write-Host ""
Write-Host "Vista Platform Device Agent Installer (Windows)" -ForegroundColor Cyan
Write-Host "===============================================" -ForegroundColor Cyan
Write-Info "Agent version : $AgentVersion"
Write-Info "Platform      : $Url"
Write-Info "Key           : $maskedKey"
Write-Info "Install dir   : $InstallDir"
if ($CaFingerprint) { Write-Info "CA fingerprint: $CaFingerprint" }
Write-Host ""

# --- Layout ----------------------------------------------------------------
$DataDir    = Join-Path $InstallDir "data"
$ConfigPath = Join-Path $InstallDir "device-agent.yaml"
# The agent writes its log here when it runs as a service (stderr goes nowhere
# under the Service Control Manager); it rotates at 10 MB to device-agent.log.1.
$LogFile    = Join-Path $DataDir "logs\device-agent.log"
$uuidPattern = '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'

# A host this key already enrolled keeps its identity. Re-running the same
# install command (to upgrade the binary, or by mistake) must not discard the
# certificate and agent ID and send it back to enroll with a key it has
# already spent. A different key means a fresh enrollment.
$keepEnrollment = Test-EnrolledWithKey $ConfigPath $Key
if ($keepEnrollment) {
    Write-Info "This host is already enrolled with this key (agent $(Get-ConfigValue $ConfigPath 'agent_id')); keeping its identity and configuration."
}

# Stop a previous install: its binary cannot be replaced while it runs, and it
# must not rewrite the config while we replace it.
if (Get-Service -Name $ServiceName -ErrorAction SilentlyContinue) {
    Stop-Service -Name $ServiceName -Force -ErrorAction SilentlyContinue
}

New-Item -ItemType Directory -Force -Path $InstallDir, $DataDir | Out-Null

# --- Administrators and SYSTEM only ----------------------------------------
# The configuration holds the registration key until the agent redeems it, and
# data\certs holds the agent's private key. Program Files lets every user read
# what is under it, and the agent rewrites its config by replacing the file, so
# the protection is on the directory: inherited by everything created in it,
# then reset onto anything an earlier install left. SIDs, not names, so it
# works on a localised Windows: S-1-5-18 is SYSTEM, S-1-5-32-544 Administrators.
& icacls.exe $InstallDir /inheritance:r /grant:r "*S-1-5-18:(OI)(CI)F" "*S-1-5-32-544:(OI)(CI)F" /Q | Out-Null
if ($LASTEXITCODE -ne 0) {
    Write-Err "Could not restrict $InstallDir to Administrators and SYSTEM (icacls exit $LASTEXITCODE). Nothing was written."
    exit 1
}
if (Get-ChildItem -LiteralPath $InstallDir -Force) {
    & icacls.exe (Join-Path $InstallDir "*") /reset /T /C /Q | Out-Null
    if ($LASTEXITCODE -ne 0) {
        Write-Err "Could not reset the permissions under $InstallDir (icacls exit $LASTEXITCODE). Nothing was written."
        exit 1
    }
}

# A fresh enrollment must not inherit a previous agent's certificate.
if (-not $keepEnrollment) {
    $staleCerts = Join-Path $DataDir "certs"
    if (Test-Path -LiteralPath $staleCerts) { Remove-Item -Recurse -Force -LiteralPath $staleCerts }
}

Write-Info "Installing device agent binary..."
Copy-Item -Force -LiteralPath $BinarySource -Destination (Join-Path $InstallDir $InstalledBinaryName)

# --- Configuration ---------------------------------------------------------
# The installer does NOT register the agent. The agent enrolls itself on first
# start: it generates its keypair locally (the private key never leaves the
# host), sends a CSR, and rewrites this file with the agent ID the platform
# accepted and the paths of the certificate it was issued.
if (-not $keepEnrollment) {
    Write-Info "Writing configuration to $ConfigPath"
    # UTF-8 without a BOM (Windows PowerShell's Out-File -Encoding utf8 adds one).
    [System.IO.File]::WriteAllText($ConfigPath, (New-AgentConfigText $Url $Key $DataDir), (New-Object System.Text.UTF8Encoding $false))
}

# --- Install + start the Windows service ----------------------------------
# Auto-start (survives a reboot) and restart-on-failure: the Windows
# equivalent of the systemd unit's WantedBy=multi-user.target and
# Restart=always.
Write-Info "Installing Windows service '$ServiceName'..."
$binPath = "`"$InstallDir\$InstalledBinaryName`" -config `"$ConfigPath`" -interactive=false"
if ($CaFingerprint) {
    # Pins the platform's CA on first start, verified against this
    # fingerprint; ignored once a CA is in the config.
    $binPath += " -ca-fingerprint $CaFingerprint"
}

$existing = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
if ($existing) {
    Write-Warn "Service already exists - reconfiguring."
    # sc.exe is the reliable way to rewrite binPath on an existing service.
    sc.exe config $ServiceName binPath= "$binPath" start= auto | Out-Null
} else {
    New-Service -Name $ServiceName -DisplayName $ServiceDisplay `
        -BinaryPathName $binPath -StartupType Automatic `
        -Description "Vista Platform device interrogation agent" | Out-Null
}

# Restart on failure: reset the failure count daily, restart after 10s on each
# of the first three failures (the SCM repeats the last action for any later
# one). The failure flag makes the SCM act on the agent's own failure exit
# code too, which is how it honours a restart requested from the console.
sc.exe failure $ServiceName reset= 86400 actions= restart/10000/restart/10000/restart/10000 | Out-Null
sc.exe failureflag $ServiceName 1 | Out-Null

# Log lines this start wrote: everything past the log's current end. The
# agent keeps the file open, so share it for writing and for its rotation.
$logStartOffset = 0
if (Test-Path -LiteralPath $LogFile) { $logStartOffset = (Get-Item -LiteralPath $LogFile).Length }
function Get-NewLogText {
    if (-not (Test-Path -LiteralPath $LogFile)) { return "" }
    try {
        $stream = [System.IO.File]::Open($LogFile, 'Open', 'Read', 'ReadWrite, Delete')
        try {
            # A rotation since we started means the whole current file is new.
            if ($stream.Length -ge $logStartOffset) { [void]$stream.Seek($logStartOffset, 'Begin') }
            $reader = New-Object System.IO.StreamReader($stream, [System.Text.Encoding]::UTF8)
            return $reader.ReadToEnd()
        } finally { $stream.Dispose() }
    } catch { return "" }
}

Write-Info "Starting the device agent; it enrolls itself with the platform..."
# An agent that exits during startup (a rejected key does) makes Start-Service
# throw; the log says why, so carry on to the checks below.
$startError = $null
try {
    Start-Service -Name $ServiceName
} catch {
    $startError = $_.Exception.Message
}

# --- Wait for enrollment ---------------------------------------------------
# Enrollment is confirmed only by the agent itself: it rewrites agent_id with
# the ID the platform accepted. A running service is not an enrolled agent.
$timeoutSeconds = 90
Write-Info "Waiting up to ${timeoutSeconds}s for the agent to enroll..."
$agentId = $null
$rejected = $false
$deadline = (Get-Date).AddSeconds($timeoutSeconds)
while ((Get-Date) -lt $deadline) {
    $value = Get-ConfigValue $ConfigPath 'agent_id'
    if ($value -match $uuidPattern) { $agentId = $value; break }
    if ((Get-NewLogText) -match 'Registration was REJECTED|cannot store its enrollment') { $rejected = $true; break }
    Start-Sleep -Seconds 2
}

$svc = Get-Service -Name $ServiceName
if (-not $agentId) {
    Write-Host ""
    # The agent marks failures with these emoji. Built from code points: this
    # file has no BOM, so Windows PowerShell reads it as ANSI, not UTF-8.
    $failureMarks = "$([char]::ConvertFromUtf32(0x26D4))|$([char]::ConvertFromUtf32(0x274C))"
    (Get-NewLogText) -split "`r?`n" | Where-Object { $_ -match $failureMarks } |
        Select-Object -Last 8 | ForEach-Object { Write-Host "  $_" }
    Write-Host ""
    if ($rejected) {
        # A rejected key never succeeds; stop the service rather than leave the
        # SCM restarting it every 10 seconds. Disable first so a restart the
        # SCM has already queued cannot start it.
        Set-Service -Name $ServiceName -StartupType Disabled -ErrorAction SilentlyContinue
        Stop-Service -Name $ServiceName -Force -ErrorAction SilentlyContinue
        Write-Err "The agent could not enroll (see above). If the key was rejected it is invalid, expired, or already used."
        Write-Err "Generate a new key (Discovery -> Sensors & Agents -> Register -> Device agent) and re-run this installer with it."
        Write-Info "The device agent service has been stopped and disabled."
    } else {
        if ($startError) { Write-Err "Starting the service failed: $startError" }
        Write-Err "The agent did not enroll within ${timeoutSeconds}s (service status: $($svc.Status))."
        Write-Info "It keeps retrying; check that $Url is reachable from this host."
        Write-Info "Log: $LogFile"
    }
    exit 1
}
if ($svc.Status -ne 'Running') {
    Write-Err "The agent enrolled but the service is not running (status: $($svc.Status))."
    Write-Info "Log: $LogFile"
    exit 1
}

Write-Host ""
Write-Info "Device agent enrolled and running."
Write-Info "Agent ID      : $agentId"
Write-Info "Agent version : $AgentVersion"
Write-Info "Configuration : $ConfigPath"
Write-Host ""
Write-Host "Management:" -ForegroundColor Cyan
Write-Host "  Status:    Get-Service $ServiceName"
Write-Host "  Logs:      Get-Content -Tail 50 -Wait '$LogFile'"
Write-Host "  Events:    Get-WinEvent -FilterHashtable @{LogName='Application'; ProviderName='$ServiceName'} -MaxEvents 20"
Write-Host "  Restart:   Restart-Service $ServiceName"
Write-Host "  Uninstall: Stop-Service $ServiceName; sc.exe delete $ServiceName"
Write-Host ""
Write-Info "The agent polls for interrogation jobs. It appears under Discovery -> Sensors & Agents once its first heartbeat arrives."
