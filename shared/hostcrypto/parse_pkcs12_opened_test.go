// What "opened" means for a PKCS#12 file:
//
//   - no_password only when the empty password opens what the file protects
//     (its MAC verifies with it, or an encrypted part decrypts with it), or
//     nothing in the file is protected by a password;
//   - aliases and certificates in a plain part are listed whatever the
//     password, and never by themselves make a store no_password;
//   - the empty password is tried with the opt-in on or off, in both its
//     encodings; the well-known defaults only with it, and default_password
//     stays nil without it.
//
// Every file here is generated by the test. The OpenSSL 3 layout is the one
// `openssl pkcs12 -export` writes by default: the certificates in an
// encrypted part (PBES2, PBKDF2-HMAC-SHA256, AES-256-CBC), the key as a
// shrouded bag in a PLAIN data part whose friendlyName and localKeyID are in
// clear, and an HMAC-SHA256 MAC.

// ksMacBMP spells a password for the PKCS#12 KDF. zeroLength gives the empty
// password as no bytes at all instead of a terminated empty BMPString.
func ksMacBMP(pw string, zeroLength bool) []byte {
	if pw == "" && zeroLength {
		return nil
	}
	var b []byte
	for _, r := range pw {
		b = append(b, byte(r>>8), byte(r))
	}
	return append(b, 0, 0)
}

// ksBuildPFXWithMac assembles parts under a MAC keyed by bmp, with the hash
// the MAC is named after (SHA-256 as OpenSSL 3 writes, SHA-1 as the legacy
// writers do).
func ksBuildPFXWithMac(t testing.TB, bmp []byte, legacy bool, parts ...ksContentInfo) []byte {
	t.Helper()
	authSafe, err := asn1.Marshal(parts)
	if err != nil {
		t.Fatal(err)
	}
	osb, _ := asn1.Marshal(authSafe)
	ci := ksContentInfo{ContentType: ksOIDData, Content: ksExplicit0(osb)}
	newHash, u, oid := sha256.New, 32, ksTestOIDSHA256
	iters := 2048
	if legacy {
		newHash, u, oid, iters = sha1.New, 20, asn1.ObjectIdentifier{1, 3, 14, 3, 2, 26}, 1
	}
	salt := []byte("macsalt!")
	key := ksP12KDF(newHash, u, 64, 3, salt, bmp, iters, u)
	mac := hmac.New(newHash, key)
	mac.Write(authSafe)
	pfx, err := asn1.Marshal(ksPFX{Version: 3, AuthSafe: ci, MacData: ksMacData{
		Mac:     ksDigestInfo{Algorithm: ksAlgorithmIdentifier{Algorithm: oid, Parameters: asn1.NullRawValue}, Digest: mac.Sum(nil)},
		MacSalt: salt, Iterations: iters,
	}})
	if err != nil {
		t.Fatal(err)
	}
	return pfx
}

// ksLegacyRC2Part encrypts bags with pbeWithSHAAnd40BitRC2-CBC, the scheme
// the legacy writers use for the certificate part, keyed by bmp.
func ksLegacyRC2Part(t testing.TB, bmp []byte, bags ...ksSafeBag) ksContentInfo {
	t.Helper()
	sc, err := asn1.Marshal(bags)
	if err != nil {
		t.Fatal(err)
	}
	salt, iters := []byte("rc2salt!"), 2048
	key := ksP12KDF(sha1.New, 20, 64, 1, salt, bmp, iters, 5)
	iv := ksP12KDF(sha1.New, 20, 64, 2, salt, bmp, iters, 8)
	n := 8 - len(sc)%8
	for i := 0; i < n; i++ {
		sc = append(sc, byte(n))
	}
	cipher.NewCBCEncrypter(ksNewRC2(key, 40), iv).CryptBlocks(sc, sc)
	params, err := asn1.Marshal(ksPBEParams{Salt: salt, Iterations: iters})
	if err != nil {
		t.Fatal(err)
	}
	type eci struct {
		ContentType asn1.ObjectIdentifier
		Alg         ksAlgorithmIdentifier
		Content     []byte `asn1:"tag:0,optional"`
	}
	ed, err := asn1.Marshal(struct {
		Version int
		ECI     eci
	}{0, eci{ksOIDData, ksAlgorithmIdentifier{Algorithm: asn1.ObjectIdentifier{1, 2, 840, 113549, 1, 12, 1, 6}, Parameters: asn1.RawValue{FullBytes: params}}, sc}})
	if err != nil {
		t.Fatal(err)
	}
	return ksContentInfo{ContentType: ksOIDEncryptedData, Content: ksExplicit0(ed)}
}

// ksOpenedWant is one expectation: Opened, DefaultPassword (nil, false or
// true), and how many certificates are listed.
type ksOpenedWant struct {
	opened string
	deflt  *bool
	certs  int
}

func TestParsePKCS12_OpenedMeansTheProtectionOpened(t *testing.T) {
	yes, no := boolPtrEmptyPw(true), boolPtrEmptyPw(false)
	key := ksTestECDSA(t)
	leaf := ksTestCert(t, key, "server", false)
	keyID := []byte("key-id-1")
	const alias = "server-key"
	secret := ksRandKey(t, 64) // stands in for the shrouded key's ciphertext
	keyBag := func() ksSafeBag {
		return ksShroudedSafeBag(t, 2048, secret, ksAttrName(t, alias), ksAttrKeyID(t, keyID))
	}
	certBag := func() ksSafeBag { return ksCertSafeBag(t, leaf.Raw, ksAttrName(t, alias), ksAttrKeyID(t, keyID)) }

	// The OpenSSL 3 layout under a password, the MAC keyed by the given
	// encoding of it.
	openssl3 := func(pw string, zeroLength bool) []byte {
		return ksBuildPFXWithMac(t, ksMacBMP(pw, zeroLength), false,
			ksEncryptedPart(t, pw, 2048, certBag()),
			ksDataPart(t, keyBag()))
	}
	// The legacy layout written here: the certificate under RC2-40, the key
	// shrouded in a plain part, a SHA-1 MAC; all keyed by one encoding.
	legacy := func(pw string, zeroLength bool) []byte {
		bmp := ksMacBMP(pw, zeroLength)
		return ksBuildPFXWithMac(t, bmp, true, ksLegacyRC2Part(t, bmp, certBag()), ksDataPart(t, keyBag()))
	}
	// Certificates in a plain bag, the key shrouded, the MAC under pw.
	plainCerts := func(pw string) []byte {
		return ksBuildPFXWithMac(t, ksMacBMP(pw, false), false, ksDataPart(t, certBag(), keyBag()))
	}

	fx := ksMakeP12Fixture(t)
	library := func(enc *pkcs12.Encoder, pw string) []byte {
		b, err := enc.Encode(fx.key, fx.leaf, nil, pw)
		if err != nil {
			t.Fatal(err)
		}
		return b
	}

	for _, tc := range []struct {
		name     string
		b        []byte
		off, on  ksOpenedWant
		aliasKey bool // the key entry carries our alias (our builders write one)
	}{
		// The rehearsal's two files.
		{"OpenSSL 3 layout, changeit", openssl3("changeit", false), ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedDefaultPassword, yes, 1}, true},
		{"OpenSSL 3 layout, empty (terminated)", openssl3("", false), ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}, true},
		{"OpenSSL 3 layout, empty (zero-length)", openssl3("", true), ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}, true},
		{"OpenSSL 3 layout, a real password", openssl3("Real-Pass-7", false), ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedNot, no, 0}, true},

		{"legacy RC2-40 + SHA-1 MAC, changeit", legacy("changeit", false), ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedDefaultPassword, yes, 1}, true},
		{"legacy RC2-40 + SHA-1 MAC, empty (terminated)", legacy("", false), ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}, true},
		{"legacy RC2-40 + SHA-1 MAC, empty (zero-length)", legacy("", true), ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}, true},
		{"legacy RC2-40 + SHA-1 MAC, a real password", legacy("Real-Pass-7", false), ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedNot, no, 0}, true},
		{"library LegacyDES (3DES), changeit", library(pkcs12.LegacyDES, "changeit"), ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedDefaultPassword, yes, 1}, false},
		{"library LegacyDES (3DES), empty", library(pkcs12.LegacyDES, ""), ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}, false},
		{"library LegacyRC2, changeit", library(pkcs12.LegacyRC2, "changeit"), ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedDefaultPassword, yes, 1}, false},
		{"library LegacyRC2, empty", library(pkcs12.LegacyRC2, ""), ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}, false},

		// The certificate is readable in clear; the MAC (and the key) need
		// the password. Listed, and not opened.
		{"plain certificates, key and MAC under a real password", plainCerts("Real-Pass-7"), ksOpenedWant{OpenedNot, nil, 1}, ksOpenedWant{OpenedNot, no, 1}, true},
		{"plain certificates, key and MAC under changeit", plainCerts("changeit"), ksOpenedWant{OpenedNot, nil, 1}, ksOpenedWant{OpenedDefaultPassword, yes, 1}, true},
		{"plain certificates, MAC under the empty password", plainCerts(""), ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}, true},

		// No MAC.
		{"no MAC, plain certificate, shrouded key", ksBuildPFX(t, nil, ksDataPart(t, certBag(), keyBag())), ksOpenedWant{OpenedNot, nil, 1}, ksOpenedWant{OpenedNot, nil, 1}, true},
		{"no MAC, certificate part under changeit", ksBuildPFX(t, nil, ksEncryptedPart(t, "changeit", 2048, certBag()), ksDataPart(t, keyBag())), ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedDefaultPassword, yes, 1}, true},
		{"no MAC, certificate part under the empty password", ksBuildPFX(t, nil, ksEncryptedPart(t, "", 2048, certBag()), ksDataPart(t, keyBag())), ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}, true},
		{"no MAC, nothing protected", ksBuildPFX(t, nil, ksDataPart(t, certBag())), ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, nil, 1}, false},
	} {
		for _, try := range []bool{false, true} {
			w := tc.off
			if try {
				w = tc.on
			}
			label := tc.name + map[bool]string{false: " (opt-in off)", true: " (opt-in on)"}[try]
			got, err := ParsePKCS12(tc.b, try)
			if err != nil {
				t.Fatalf("%s: %v", label, err)
			}
			ks := got.Keystore
			if ks.Opened != w.opened {
				t.Errorf("%s: opened %q, want %q (unknown %q)", label, ks.Opened, w.opened, ks.Unknown)
			}
			if (ks.DefaultPassword == nil) != (w.deflt == nil) || (ks.DefaultPassword != nil && *ks.DefaultPassword != *w.deflt) {
				t.Errorf("%s: default_password %v, want %v (not tried %q)", label, ks.DefaultPassword, w.deflt, got.DefaultsNotTried)
			}
			if !try && got.DefaultsNotTried != "" {
				t.Errorf("%s: without the opt-in DefaultsNotTried is %q", label, got.DefaultsNotTried)
			}
			if len(got.Certificates) != w.certs {
				t.Errorf("%s: %d certificates listed, want %d", label, len(got.Certificates), w.certs)
			}
			// The plain part's key bag is listed either way: a readable fact.
			if pk := ksKeyEntry(ks); tc.aliasKey && (pk == nil || pk.Alias != alias) {
				t.Errorf("%s: key entry %+v, want alias %q", label, pk, alias)
			}
			if ks.Opened == OpenedNot && ks.Unknown == "" {
				t.Errorf("%s: not opened, and no reason given", label)
			}
			ksAssertNoSecret(t, label, got, secret)
			ksAssertNoSecret(t, label, got, fx.secrets...)
		}
	}
}

// TestParsePKCS12_RealOpenSSL makes the files with the host's OpenSSL 3, when
// it has one, and reads them locally: the rehearsal's case end to end.
func TestParsePKCS12_RealOpenSSL(t *testing.T) {
	if _, err := exec.LookPath("openssl"); err != nil {
		t.Skip("no openssl")
	}
	if v, err := exec.Command("openssl", "version").Output(); err != nil || !strings.HasPrefix(string(v), "OpenSSL 3") {
		t.Skip("not OpenSSL 3")
	}
	dir := t.TempDir()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	secrets := ksSecretsOf(t, key)
	der, _ := x509.MarshalPKCS8PrivateKey(key)
	tmpl := &x509.Certificate{SerialNumber: big.NewInt(9), Subject: pkix.Name{CommonName: "openssl.example.test"},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour)}
	cert, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	kp := jobWrite(t, dir, "k.pem", pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: der}), 0o600)
	cp := jobWrite(t, dir, "c.pem", pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: cert}), 0o600)
	mk := func(name, pass string, extra ...string) ([]byte, bool) {
		out := filepath.Join(dir, name)
		args := append([]string{"pkcs12", "-export", "-inkey", kp, "-in", cp, "-name", "server", "-passout", "pass:" + pass, "-out", out}, extra...)
		if b, err := exec.Command("openssl", args...).CombinedOutput(); err != nil {
			t.Logf("openssl %v: %v %s", extra, err, b)
			return nil, false
		}
		b, err := os.ReadFile(out)
		if err != nil {
			t.Fatal(err)
		}
		return b, true
	}
	yes, no := boolPtrEmptyPw(true), boolPtrEmptyPw(false)
	for _, tc := range []struct {
		name    string
		pass    string
		extra   []string
		off, on ksOpenedWant
	}{
		{"default layout, changeit", "changeit", nil, ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedDefaultPassword, yes, 1}},
		{"default layout, empty", "", nil, ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}},
		{"default layout, a real password", "Real-Pass-7", nil, ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedNot, no, 0}},
		{"legacy, changeit", "changeit", []string{"-legacy"}, ksOpenedWant{OpenedNot, nil, 0}, ksOpenedWant{OpenedDefaultPassword, yes, 1}},
		{"legacy, empty", "", []string{"-legacy"}, ksOpenedWant{OpenedWithoutPassword, nil, 1}, ksOpenedWant{OpenedWithoutPassword, no, 1}},
		{"plain certificates, a real password", "Real-Pass-7", []string{"-certpbe", "NONE"}, ksOpenedWant{OpenedNot, nil, 1}, ksOpenedWant{OpenedNot, no, 1}},
		{"plain certificates, no MAC, a real password", "Real-Pass-7", []string{"-certpbe", "NONE", "-nomac"}, ksOpenedWant{OpenedNot, nil, 1}, ksOpenedWant{OpenedNot, nil, 1}},
	} {
		b, ok := mk(strings.ReplaceAll(tc.name, " ", "_")+".p12", tc.pass, tc.extra...)
		if !ok {
			t.Logf("%s: this OpenSSL cannot write it; skipped", tc.name)
			continue
		}
		for _, try := range []bool{false, true} {
			w := tc.off
			if try {
				w = tc.on
			}
			got, err := ParsePKCS12(b, try)
			if err != nil {
				t.Fatalf("%s: %v", tc.name, err)
			}
			ks := got.Keystore
			if ks.Opened != w.opened || (ks.DefaultPassword == nil) != (w.deflt == nil) || (ks.DefaultPassword != nil && *ks.DefaultPassword != *w.deflt) || len(got.Certificates) != w.certs {
				t.Errorf("%s (opt-in %v): opened %q default %v, %d certificates; want %q %v %d (%q)", tc.name, try, ks.Opened, ks.DefaultPassword, len(got.Certificates), w.opened, w.deflt, w.certs, got.DefaultsNotTried)
			}
			if pk := ksKeyEntry(ks); pk == nil || pk.Alias != "server" {
				t.Errorf("%s (opt-in %v): key entry %+v", tc.name, try, pk)
			}
			ksAssertNoSecret(t, tc.name, got, secrets...)
		}
	}
}
